/**
 * Pre-deploy check: proves each production value works BEFORE you paste it into
 * Render. Never prints a secret — only ✓ / ✗ and what to fix.
 *
 *   npm run check:deploy -- --env .env.production      (a git-ignored file you create)
 *   npm run check:deploy                               (uses the current environment)
 *
 * Checks: MongoDB Atlas connects and answers a ping; the Claude key answers on
 * each configured model; the Google client ID looks right; the Web Push key pair
 * matches; subject and public URL formats.
 */

import fs from 'fs';
import crypto from 'crypto';
import dotenv from 'dotenv';
import mongoose from 'mongoose';
import Anthropic from '@anthropic-ai/sdk';

const i = process.argv.indexOf('--env');
const env = i > 0 ? dotenv.parse(fs.readFileSync(process.argv[i + 1])) : { ...process.env };

// VAPID keys generated by this repo (backend/.data/vapid-production.json) count if not set explicitly
if ((!env.VAPID_PUBLIC_KEY || !env.VAPID_PRIVATE_KEY) && fs.existsSync('.data/vapid-production.json')) {
  Object.assign(env, JSON.parse(fs.readFileSync('.data/vapid-production.json', 'utf8')));
  env._vapidFromFile = '1';
}

const results = [];
const ok = (name, detail = '') => results.push({ s: '✓', name, detail });
const bad = (name, detail) => results.push({ s: '✗', name, detail });
const skip = (name, detail) => results.push({ s: '–', name, detail });

// 1. MongoDB Atlas
if (!env.MONGODB_URI) bad('MONGODB_URI', 'missing — Atlas → Connect → Drivers');
else if (!/^mongodb(\+srv)?:\/\//.test(env.MONGODB_URI)) bad('MONGODB_URI', 'must start with mongodb+srv:// or mongodb://');
else {
  try {
    const conn = await mongoose.createConnection(env.MONGODB_URI, { serverSelectionTimeoutMS: 10000 }).asPromise();
    await conn.db.admin().ping();
    const name = conn.db.databaseName;
    await conn.close();
    if (name === 'test') skip('MONGODB_URI', 'connects, but no database name — add /vexa before the ? (data would go to "test")');
    else ok('MONGODB_URI', `connects · database "${name}"`);
  } catch (e) {
    const m = String(e.message);
    bad('MONGODB_URI', /auth|Authentication/i.test(m) ? 'wrong user or password' : /ENOTFOUND|querySrv/i.test(m) ? 'host not found — copy the string again' : /timed out|Server selection/i.test(m) ? 'timed out — Atlas → Network Access → add 0.0.0.0/0' : m.slice(0, 120));
  }
}

// 2. Claude
if (!env.ANTHROPIC_API_KEY) bad('ANTHROPIC_API_KEY', 'missing — without it Vexa runs on offline rules only');
else {
  const client = new Anthropic({ apiKey: env.ANTHROPIC_API_KEY, maxRetries: 0, timeout: 20000 });
  for (const [label, model] of [['ANTHROPIC_MODEL', env.ANTHROPIC_MODEL || 'claude-opus-5-5'], ['ANTHROPIC_FAST_MODEL', env.ANTHROPIC_FAST_MODEL]]) {
    if (!model) { skip(label, 'not set (optional)'); continue; }
    try {
      await client.messages.create({ model, max_tokens: 1, messages: [{ role: 'user', content: 'hi' }] });
      ok(label, `${model} answers`);
    } catch (e) {
      bad(label, e.status === 401 ? 'API key rejected' : e.status === 404 ? `model "${model}" not available to this key` : `${e.status || ''} ${String(e.message).slice(0, 100)}`);
    }
  }
}

// 3. Google sign-in
if (!env.GOOGLE_CLIENT_ID) bad('GOOGLE_CLIENT_ID', 'missing — without it (and without SMS) nobody can sign in on the hosted app');
else if (!/^\d+-[a-z0-9]+\.apps\.googleusercontent\.com$/.test(env.GOOGLE_CLIENT_ID)) bad('GOOGLE_CLIENT_ID', 'should look like 1234-abc….apps.googleusercontent.com (the Client ID, not the secret)');
else ok('GOOGLE_CLIENT_ID', 'format OK — remember to add your Render URL under Authorized JavaScript origins');

// 4. Web Push key pair
if (!env.VAPID_PUBLIC_KEY || !env.VAPID_PRIVATE_KEY) bad('VAPID keys', 'missing — npx web-push generate-vapid-keys');
else {
  try {
    const ecdh = crypto.createECDH('prime256v1');
    ecdh.setPrivateKey(Buffer.from(env.VAPID_PRIVATE_KEY, 'base64url'));
    const match = ecdh.getPublicKey().toString('base64url') === env.VAPID_PUBLIC_KEY;
    if (match) ok('VAPID keys', `public and private keys match${env._vapidFromFile ? ' (from backend/.data/vapid-production.json)' : ''}`);
    else bad('VAPID keys', 'public key does not belong to the private key — copy both from the same run');
  } catch {
    bad('VAPID keys', 'private key is not a valid key');
  }
}
if (!env.VAPID_SUBJECT) bad('VAPID_SUBJECT', 'missing — mailto:you@yourdomain');
else if (!/^(mailto:\S+@\S+|https:\/\/\S+)$/.test(env.VAPID_SUBJECT)) bad('VAPID_SUBJECT', 'must be mailto:you@example.com or an https:// URL');
else ok('VAPID_SUBJECT', 'format OK');

// 5. Optional
if (env.PUBLIC_URL && !/^https:\/\/[^/]+$/.test(env.PUBLIC_URL.replace(/\/$/, ''))) bad('PUBLIC_URL', 'must be https://host with no path (Render sets this itself — you can leave it out)');
else skip('PUBLIC_URL', env.PUBLIC_URL ? 'set' : 'not needed on Render (RENDER_EXTERNAL_URL is automatic)');
skip('JWT_SECRET, STREAM_TOKEN_SECRET', 'Render generates these from render.yaml');

const w = Math.max(...results.map(r => r.name.length));
console.log('\nVexa pre-deploy check\n');
for (const r of results) console.log(` ${r.s}  ${r.name.padEnd(w)}  ${r.detail}`);
const failed = results.filter(r => r.s === '✗').length;
console.log(failed ? `\n${failed} problem(s) to fix before deploying.\n` : '\nAll set — paste these values into Render (see docs/DEPLOY.md step 4).\n');
process.exit(failed ? 1 : 0);
